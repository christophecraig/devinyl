/**
 * Worker entry point — wraps the SvelteKit build so the app can also answer Cron
 * Triggers.
 *
 * WHY THIS FILE EXISTS
 * `@sveltejs/adapter-cloudflare` (7.x) emits a Worker exporting only `fetch`; it
 * has no option to also export `scheduled`. The plan's deviation table replaces
 * the tech spec's in-process `setInterval` jobs (§15) with two Cron Triggers
 * dispatching through a single `runJobs(kind)` entry, so we need `scheduled`.
 *
 * The fix is this thin wrapper: it re-exports the generated handler's `fetch`
 * untouched and adds `scheduled` beside it. Wrangler bundles this file (and the
 * TypeScript job code it imports) as the real entry.
 *
 * THE TWO-CONFIG SPLIT
 * The adapter writes its generated Worker to the `main` path of whichever
 * wrangler config it reads. Pointed at this file, it would overwrite it on every
 * build. So the adapter reads `wrangler.build.jsonc` (main → the generated
 * artifact) while `wrangler.jsonc` — the config `wrangler dev`/`deploy` use —
 * points `main` here.
 *
 * WHY IT LIVES OUTSIDE `src/`
 * `svelte-check` walks `src/**`. Importing the generated `_worker.js` from inside
 * `src/` drags the whole compiled SvelteKit server bundle into type-checking,
 * which never type-checks cleanly. Keeping the wrapper here means the checker
 * never sees it, while the job code it calls stays fully checked in
 * `src/lib/server/jobs/`.
 *
 * BUILD ORDER: `vite build` must run before `wrangler deploy|dev`, because the
 * import below resolves to a build artifact. `pnpm run build` already does this.
 */

// The generated Worker is a build artifact: untyped, and absent entirely until
// `vite build` has run. `@ts-ignore` rather than `@ts-expect-error` on purpose —
// the import errors on a fresh checkout but resolves after a build, and
// `@ts-expect-error` would itself become an error in the second case.
// The suppression must survive the line becoming error-free after a build,
// which is exactly what @ts-expect-error cannot do — hence the rule exemption.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore - generated by adapter-cloudflare at build time
import generated from '../.svelte-kit/cloudflare/_worker.js';

import { runJobs, type JobKind } from '../src/lib/server/jobs/index.js';

const app = generated as { fetch: ExportedHandlerFetchHandler };

/**
 * Map a cron expression to the job batch it drives. The mapping lives here
 * rather than inside `runJobs` so the schedules declared in wrangler.jsonc and
 * the job kinds they trigger stay legible side by side.
 */
function jobKindFor(cron: string): JobKind | null {
	switch (cron) {
		case '*/15 * * * *':
			return 'every-15-min';
		case '0 * * * *':
			return 'hourly';
		case '5 0 * * *':
			return 'daily';
		default:
			return null;
	}
}

export default {
	fetch: app.fetch,

	async scheduled(event, env, ctx) {
		const kind = jobKindFor(event.cron);
		if (!kind) {
			// A schedule added to wrangler.jsonc without a mapping here would
			// otherwise fire into silence.
			console.error(`No job batch mapped to cron "${event.cron}" — nothing ran.`);
			return;
		}

		// `waitUntil` keeps the isolate alive for the whole batch; without it a slow
		// sweep can be cut off mid-flight.
		ctx.waitUntil(
			runJobs(kind, { env, ctx } as unknown as App.Platform).catch((error: unknown) => {
				// A thrown job must not take the batch down silently — surface it in
				// `wrangler tail` (the §15 observability story).
				console.error(`Job batch "${kind}" failed:`, error);
			})
		);
	}
} satisfies ExportedHandler<Env>;
